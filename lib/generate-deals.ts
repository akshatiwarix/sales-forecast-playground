import { AS_OF_DATE, STAGES } from "./types.ts";
import type { Deal, Stage } from "./types.ts";

function mulberry32(seed: number) {
  let state = seed;
  return function random() {
    state |= 0;
    state = (state + 0x6d2b79f5) | 0;
    let t = Math.imul(state ^ (state >>> 15), 1 | state);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const rand = mulberry32(31); // seed = day number in the 100-day series

function pick<T>(pool: T[]): T {
  return pool[Math.floor(rand() * pool.length)];
}

function daysFromAsOf(days: number): string {
  const d = new Date(`${AS_OF_DATE}T00:00:00Z`);
  d.setUTCDate(d.getUTCDate() + days);
  return d.toISOString().slice(0, 10);
}

