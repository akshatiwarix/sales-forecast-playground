function randIn([min, max]: [number, number]): number {
  return min + rand() * (max - min);
}

const usedAccounts = new Set<string>();
function nextAccount(): string {
  const available = ACCOUNTS.filter((a) => !usedAccounts.has(a));
  const pool = available.length > 0 ? available : ACCOUNTS;
  const chosen = pick(pool);
  usedAccounts.add(chosen);
  return chosen;
}

const deals: Deal[] = [];
let counter = 1;

for (const stage of STAGES) {
  const config = STAGE_CONFIG[stage];
  for (let i = 0; i < config.count; i++) {
    const inQuarter = rand() < config.inQuarterShare;
    const closeDays = Math.round(
      inQuarter ? randIn(config.closeDaysInQuarter) : randIn(config.closeDaysNextQuarter),
    );
    const stageEnteredDays = -Math.round(5 + rand() * 55);

    deals.push({
      id: `deal-${String(counter).padStart(3, "0")}`,
      account: nextAccount(),
      owner: pick(OWNERS),
      amount: Math.round(randIn(config.amount) / 500) * 500,
      stage,
      stageEnteredDate: daysFromAsOf(stageEnteredDays),
      expectedCloseDate: daysFromAsOf(closeDays),
      repProbability: Math.round(randIn(config.probability) * 100) / 100,
    });
    counter++;
  }
}

if (deals.length !== 200) {
  throw new Error(`Expected 200 deals, built ${deals.length}`);
}

const body = deals
  .map((d) => {
    return `  {
    id: "${d.id}",
    account: "${d.account}",
    owner: "${d.owner}",
    amount: ${d.amount},
    stage: "${d.stage}",
    stageEnteredDate: "${d.stageEnteredDate}",
    expectedCloseDate: "${d.expectedCloseDate}",
    repProbability: ${d.repProbability},
  }`;
  })
  .join(",\n");

